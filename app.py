
import streamlit as st
import joblib

# Load the trained ML model

model = joblib.load("spam_classifier.pkl")

# Page configuration

st.set_page_config(
    page_title="SMS Spam Detector",
    page_icon="📩",
    layout="centered"
)

# Application heading

st.title("📩 SMS Spam Detection System")

st.write(
    "An intelligent SMS classification system "
    "using Natural Language Processing and Machine Learning."
)

st.divider()

# Message input

st.subheader("Enter Your SMS Message")

message = st.text_area(
    "Type or paste your message below:",
    placeholder="Enter your SMS message here...",
    height=150
)

# Example messages

st.write("Try an example:")

col1, col2 = st.columns(2)

with col1:
    if st.button("Spam Example"):
        st.session_state["example"] = (
            "Congratulations! You have won a free prize. "
            "Call now to claim your reward!"
        )

with col2:
    if st.button("Normal Example"):
        st.session_state["example"] = (
            "Hey, are you coming to college tomorrow? "
            "We have a class at 10 AM."
        )

if "example" in st.session_state:
    message = st.session_state["example"]

# Prediction button

if st.button("Check Message", type="primary"):

    if message.strip() == "":
        st.warning("Please enter a message first.")

    else:

        # Predict the message category

        prediction = model.predict([message])[0]

        # Calculate model-estimated probability

        probabilities = model.predict_proba([message])[0]

        predicted_index = list(model.classes_).index(
            prediction
        )

        score = probabilities[predicted_index]

        st.divider()
        st.subheader("Prediction Result")

        if prediction == "spam":

            st.error("🚨 SPAM MESSAGE DETECTED")

            st.write(
                "The model has classified this message "
                "as Spam."
            )

        else:

            st.success("✅ HAM - LEGITIMATE MESSAGE")

            st.write(
                "The model has classified this message "
                "as a normal message."
            )

        st.metric(
            "Model-estimated probability for predicted class",
            f"{score * 100:.2f}%"
        )

        st.info(
            "This prediction is generated by a trained "
            "Machine Learning model and may not always "
            "be correct."
        )

st.divider()

st.subheader("About This Application")

st.write("""
This application uses:

- TF-IDF for text feature extraction.
- Multinomial Naive Bayes for classification.
- Supervised Machine Learning for Spam and Ham detection.
""")

st.caption(
    "AIC2022 | Introduction to Artificial Intelligence"
)